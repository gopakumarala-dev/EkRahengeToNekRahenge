/* =========================================================
   CARD FILTERING
========================================================= */

const cards =
  document.getElementById("cards");

const emptyState =
  document.getElementById("emptyState");

const searchInput =
  document.getElementById("searchInput");

const categoryFilter =
  document.getElementById("categoryFilter");

const eraChips =
  document.querySelectorAll(".era-chip");


function cardMatches(story){

  const query =
    searchInput.value
      .trim()
      .toLowerCase();

  const category =
    categoryFilter.value;

  const activeEra =
    document
      .querySelector(".era-chip.active")
      ?.dataset.era || "all";


  const haystack = [

    story.title,
    story.meta,
    story.deck,
    story.summary,
    story.id,
    ...(story.category || [])

  ]
  .join(" ")
  .toLowerCase();


  const queryOK =
    !query ||
    haystack.includes(query);


  const categoryOK =
    category === "all" ||
    (story.category || [])
      .includes(category);


  const eraOK =
    activeEra === "all" ||
    story.era === activeEra;


  return (
    queryOK &&
    categoryOK &&
    eraOK
  );

}


/* =========================================================
   RENDER CARDS
========================================================= */

function renderCards(){

  const visible =
    stories.filter(cardMatches);


  cards.innerHTML =
    visible.map(story => `

      <article class="story-card">

        <img
          src="${story.image}"
          alt="${story.title}"
          loading="lazy"
          onerror="this.style.opacity='.25'"
        >

        <div class="story-card-body">

          <div class="meta">
            ${story.meta}
          </div>

          <h3>
            ${story.title}
          </h3>

          <p>
            ${story.summary}
          </p>

          <button
            class="open-story"
            data-story="${story.id}"
          >
            READ THE FULL STORY →
          </button>

        </div>

      </article>

    `)
    .join("");


  emptyState.hidden =
    visible.length !== 0;


  document
    .querySelectorAll(".open-story")
    .forEach(button => {

      button.addEventListener(
        "click",
        () => {

          openReader(
            button.dataset.story
          );

        }
      );

    });

}


searchInput.addEventListener(
  "input",
  renderCards
);

categoryFilter.addEventListener(
  "change",
  renderCards
);


eraChips.forEach(chip => {

  chip.addEventListener(
    "click",
    () => {

      eraChips.forEach(
        item =>
          item.classList.remove("active")
      );

      chip.classList.add("active");

      renderCards();

    }
  );

});


renderCards();


/* =========================================================
   FULL SCREEN ARTICLE READER
========================================================= */

const reader =
  document.getElementById("reader");

const readerImage =
  document.getElementById("readerImage");

const readerKicker =
  document.getElementById("readerKicker");

const readerTitle =
  document.getElementById("readerTitle");

const readerDeck =
  document.getElementById("readerDeck");

const readerToc =
  document.getElementById("readerToc");

const readerContent =
  document.getElementById("readerContent");


function openReader(id){

  const story =
    stories.find(
      item => item.id === id
    );

  if(!story) return;


  readerImage.src =
    story.image;

  readerImage.alt =
    story.title;


  readerKicker.textContent =
    story.meta;


  readerTitle.textContent =
    story.title;


  readerDeck.textContent =
    story.deck;


  readerToc.innerHTML =
    story.sections
      .map(
        (section,index) => `

          <button
            data-index="${index}"
          >

            ${String(index+1).padStart(2,"0")}
            •
            ${section[0]}

          </button>

        `
      )
      .join("");


  readerContent.innerHTML =
    story.sections
      .map(
        (section,index) => `

          <section
            id="reader-sec-${index}"
          >

            <h3>
              ${section[0]}
            </h3>

            ${section[1]}

          </section>

        `
      )
      .join("");


  reader.classList.add(
    "open"
  );


  reader.setAttribute(
    "aria-hidden",
    "false"
  );


  document.body.classList.add(
    "locked"
  );


  reader.scrollTop = 0;


  readerToc
    .querySelectorAll("button")
    .forEach(button => {

      button.addEventListener(
        "click",
        () => {

          const target =
            document.getElementById(
              `reader-sec-${button.dataset.index}`
            );


          if(target){

            target.scrollIntoView({

              behavior:"smooth",

              block:"start"

            });

          }

        }
      );

    });

}


function closeReader(){

  reader.classList.remove(
    "open"
  );

  reader.setAttribute(
    "aria-hidden",
    "true"
  );

  document.body.classList.remove(
    "locked"
  );

}


document
  .getElementById("readerClose")
  .addEventListener(
    "click",
    closeReader
  );


reader.addEventListener(
  "click",
  event => {

    if(
      event.target === reader
    ){

      closeReader();

    }

  }
);


